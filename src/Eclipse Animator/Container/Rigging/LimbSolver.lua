local function dracoAngle(distance)
	if distance >= dracoBend[#dracoBend][1] then
		return 0
	end

	local lo, hi = 1, #dracoBend
	while hi - lo > 1 do
		local mid = math.floor((lo + hi) / 2)
		if dracoBend[mid][1] <= distance then
			lo = mid
		else
			hi = mid
		end
	end

	local a, b = dracoBend[lo], dracoBend[hi]
	return a[2] + (b[2] - a[2]) * math.clamp((distance - a[1]) / (b[1] - a[1]), 0, 1)
end

local function plantedKnee(root, foot, pole, upperLength, reach, fallback)
	local delta = foot - root
	local direction = delta.Magnitude > EPSILON and delta.Unit or -fallback.UpVector
	local side = pole - root
	side -= direction * side:Dot(direction)
	if side.Magnitude < EPSILON then
		side = fallback.LookVector - direction * fallback.LookVector:Dot(direction)
	end

	if side.Magnitude < EPSILON then
		side = fallback.RightVector - direction * fallback.RightVector:Dot(direction)
	end

	local angle = dracoAngle(delta.Magnitude / reach)
	return root + upperLength * (direction * math.cos(angle) + side.Unit * math.sin(angle))
end

local function trackUp(frame, direction)
	if direction.Magnitude > EPSILON and frame.UpVector:Dot(direction.Unit) < -1 + 1e-6 then
		return CFrame.fromAxisAngle(frame.RightVector, math.pi) * frame.Rotation
	end

	return LimbSolver.rotationBetween(frame.UpVector, direction) * frame.Rotation
end

function LimbSolver.plantedR6(rootFrame, target, pole, size, bend)
	local h = size.Y
	local amount = math.clamp((bend or 65) / 65, 0, 100 / 65)
	local upper = Vector3.new(0, -0.087812245 * h, -0.002384424 * h) * amount
	local root = rootFrame.Position + rootFrame.UpVector * (0.025 * h)
	local foot = target.Position - target.UpVector * (0.007253408 * h)
	local restTip = Vector3.new(0, -1.032253408 * h, 0)
	local knee
	if amount < 0.0001 then
		knee = root
	else
		knee = plantedKnee(
			root,
			foot,
			pole,
			upper.Magnitude,
			upper.Magnitude + (restTip - upper).Magnitude,
			target
		)
	end

	knee = knee or root

	local restKnee = Vector3.new(0, 1.032253408 * h, 0) + upper
	local restTrack = Vector3.new(0, -0.244441092 * h, 0.002384424 * h)
	local aim = trackUp(target, knee - foot)
	local helper = foot + aim:VectorToWorldSpace(restKnee)
	local orientation = LimbSolver.rotationBetween(aim:VectorToWorldSpace(restTrack), foot - helper)
		* aim
	local center = target.Position + orientation:VectorToWorldSpace(Vector3.new(0, h * 0.5, 0))
	return CFrame.new(center) * orientation
end

return LimbSolver
