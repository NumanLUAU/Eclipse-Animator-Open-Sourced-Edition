local LimbSolver = {}
local SoftIK = require("SoftIK")

local EPSILON = 1e-6

function LimbSolver.rotationBetween(from, to)
	if from.Magnitude < EPSILON or to.Magnitude < EPSILON then
		return CFrame.identity
	end

	from, to = from.Unit, to.Unit
	local dot = math.clamp(from:Dot(to), -1, 1)
	local cross = from:Cross(to)
	if cross.Magnitude < EPSILON then
		if dot > 0 then
			return CFrame.identity
		end

		local basis = math.abs(from.X) < 0.8 and Vector3.xAxis or Vector3.yAxis
		return CFrame.fromAxisAngle(from:Cross(basis).Unit, math.pi)
	end

	return CFrame.fromAxisAngle(cross.Unit, math.atan2(cross.Magnitude, dot))
end

function LimbSolver.twoLink(root, middle, tip, goal, pole, fallback, softPercent)
	local upperLength = (middle - root).Magnitude
	local lowerLength = (tip - middle).Magnitude
	if upperLength < EPSILON or lowerLength < EPSILON then
		return nil
	end

	local delta = goal - root
	local direction = delta.Magnitude > EPSILON and delta.Unit or (tip - root)
	if direction.Magnitude < EPSILON then
		direction = middle - root
	end

	direction = direction.Unit
	local reach = upperLength + lowerLength
	local reference = math.min((tip - root).Magnitude, reach)
	local compensation = reference - SoftIK.distance(reference, reach, softPercent)
	local softened = math.min(
		delta.Magnitude,
		SoftIK.distance(delta.Magnitude, reach, softPercent) + compensation
	)
	local distance =
		math.clamp(softened, math.max(math.abs(upperLength - lowerLength), EPSILON), reach)
	local bend = pole - root
	bend -= direction * bend:Dot(direction)
	if bend.Magnitude < EPSILON then
		bend = fallback - direction * fallback:Dot(direction)
	end

	if bend.Magnitude < EPSILON then
		local basis = math.abs(direction.X) < 0.8 and Vector3.xAxis or Vector3.yAxis
		bend = basis - direction * basis:Dot(direction)
	end

	bend = bend.Unit
	local along = (upperLength * upperLength - lowerLength * lowerLength + distance * distance)
		/ (2 * distance)
	local height = math.sqrt(math.max(0, upperLength * upperLength - along * along))
	return root + direction * along + bend * height, root + direction * distance
end

